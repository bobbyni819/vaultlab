def _font(size: int) -> ImageFont.FreeTypeFont:
    """Best-effort font lookup; falls back to default if Arial unavailable."""
    candidates = [
        r"C:\Windows\Fonts\arialbd.ttf",
        r"C:\Windows\Fonts\arial.ttf",
        "/Library/Fonts/Arial Bold.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVu-Sans-Bold.ttf",
    ]
    for c in candidates:
        if os.path.exists(c):
            return ImageFont.truetype(c, size)
    return ImageFont.load_default()


def annotate_figure(plan: FigurePlan) -> Path:
    """Draw annotations on the figure; save under OUTPUT_DIR; return path."""
    src = INPUT_DIR / plan.image_filename
    img = Image.open(src).convert("RGB")
    W, H = img.size

    # Add 380px right gutter for callout text + leader lines
    GUTTER = 420
    canvas = Image.new("RGB", (W + GUTTER, H), (255, 255, 255))
    canvas.paste(img, (0, 0))
    draw = ImageDraw.Draw(canvas)

    label_font = _font(max(12, H // 60))
    body_font = _font(max(11, H // 75))

    # Place callouts down the right gutter
    n = len(plan.annotations)
    gutter_x = W + 12
    callout_top = 30
    callout_bottom = H - 30
    spacing = (callout_bottom - callout_top) / max(n, 1)

    for i, ann in enumerate(plan.annotations):
        color = COLORS[i % len(COLORS)]
        x, y, w, h = ann.bbox
        bx, by = int(x * W), int(y * H)
        bw, bh = int(w * W), int(h * H)

        # Bounding box on the figure
        draw.rectangle([(bx, by), (bx + bw, by + bh)], outline=color, width=4)

        # Numbered marker in the corner of the box
        num = str(i + 1)
        marker_size = max(28, H // 35)
        marker_xy = (bx, by - marker_size)
        draw.rectangle(
            [marker_xy, (marker_xy[0] + marker_size, marker_xy[1] + marker_size)],
            fill=color,
        )
        # Center the number in the marker
        try:
            tw, th = draw.textbbox((0, 0), num, font=label_font)[2:]
        except AttributeError:
            tw, th = label_font.getsize(num)  # type: ignore[attr-defined]
        draw.text(
            (marker_xy[0] + (marker_size - tw) / 2, marker_xy[1] + (marker_size - th) / 2 - 2),
            num, fill=(255, 255, 255), font=label_font,
        )

        # Callout in the right gutter, vertically distributed
        callout_y = int(callout_top + spacing * i)
        # Leader line from box right-edge to callout
        anchor_box = (bx + bw, by + bh // 2)
        anchor_callout = (gutter_x, callout_y + 8)
        draw.line([anchor_box, anchor_callout], fill=color, width=2)

        # Callout marker
        draw.rectangle(
            [(gutter_x - marker_size - 4, callout_y),
             (gutter_x - 4, callout_y + marker_size)],
            fill=color,
        )
        draw.text(
            (gutter_x - marker_size - 4 + (marker_size - tw) / 2,
             callout_y + (marker_size - th) / 2 - 2),
            num, fill=(255, 255, 255), font=label_font,
        )

        # Wrap label text into ~30-char lines
        wrapped = _wrap(ann.label, max_chars=34)
        for j, line in enumerate(wrapped):
            draw.text(
                (gutter_x + 2, callout_y + j * (max(11, H // 75) + 2)),
                line, fill=(20, 20, 20), font=body_font,
            )

    out = OUTPUT_DIR / f"annotated_{plan.image_filename}"
    canvas.save(out)
    return out


def _wrap(text: str, max_chars: int) -> list[str]:
    words = text.split()
    out: list[str] = []
    cur: list[str] = []
    cur_len = 0
    for w in words:
        if cur_len + len(w) + 1 > max_chars and cur:
            out.append(" ".join(cur))
            cur = [w]
            cur_len = len(w)
        else:
            cur.append(w)
            cur_len += len(w) + 1
    if cur:
        out.append(" ".join(cur))
    return out


