def build_pptx(plans: list[FigurePlan], annotated_paths: list[Path]) -> Path:
    pres = Presentation()
    pres.slide_width = Inches(13.333)
    pres.slide_height = Inches(7.5)
    blank = pres.slide_layouts[6]

    # Title slide
    s = pres.slides.add_slide(blank)
    title_box = s.shapes.add_textbox(
        Inches(0.5), Inches(2.0), Inches(12.3), Inches(2.0)
    )
    tf = title_box.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    run = p.add_run()
    run.text = "VaultLab Figure-Understanding Demo"
    run.font.name = "Arial"
    run.font.size = Pt(40)
    run.font.bold = True
    run.font.color.rgb = RGBColor(20, 20, 20)

    sub = s.shapes.add_textbox(
        Inches(0.5), Inches(4.2), Inches(12.3), Inches(2.5)
    )
    sf = sub.text_frame
    sf.word_wrap = True
    sub_text = (
        "Source: car_t_30min_v13.pptx — 8 figures from your CAR-T review deck.\n\n"
        "For each: numbered bounding-box overlays show what VaultLab identified + "
        "where on the figure. Right-side callouts are short tags; full explanations "
        "live in the speaker notes.\n\n"
        f"Generated 2026-04-29 by vaultlab figure-understanding prototype "
        f"(scripts/figure_understanding_prototype.py)."
    )
    for i, line in enumerate(sub_text.split("\n\n")):
        p = sf.paragraphs[0] if i == 0 else sf.add_paragraph()
        run = p.add_run()
        run.text = line
        run.font.name = "Arial"
        run.font.size = Pt(18)
        run.font.color.rgb = RGBColor(60, 60, 60)

    # Figure slides
    for plan, ann_path in zip(plans, annotated_paths):
        s = pres.slides.add_slide(blank)

        # Title
        title_box = s.shapes.add_textbox(
            Inches(0.4), Inches(0.2), Inches(12.5), Inches(0.7)
        )
        tf = title_box.text_frame
        tf.word_wrap = True
        p = tf.paragraphs[0]
        run = p.add_run()
        run.text = plan.title
        run.font.name = "Arial"
        run.font.size = Pt(22)
        run.font.bold = True
        run.font.color.rgb = RGBColor(20, 20, 20)

        # Annotated figure — compute size from image aspect to fit available area
        avail_w_in = 12.5
        avail_h_in = 5.6
        img = Image.open(ann_path)
        img_w, img_h = img.size
        aspect = img_w / img_h
        avail_aspect = avail_w_in / avail_h_in
        if aspect > avail_aspect:
            disp_w = Inches(avail_w_in)
            disp_h = Inches(avail_w_in / aspect)
        else:
            disp_h = Inches(avail_h_in)
            disp_w = Inches(avail_h_in * aspect)

        x_in = (13.333 - disp_w / Emu(914400)) / 2  # center
        s.shapes.add_picture(
            str(ann_path),
            Inches(x_in),
            Inches(1.0),
            width=disp_w,
            height=disp_h,
        )

        # Caption
        caption_box = s.shapes.add_textbox(
            Inches(0.4), Inches(6.7), Inches(12.5), Inches(0.7)
        )
        cf = caption_box.text_frame
        cf.word_wrap = True
        p = cf.paragraphs[0]
        run = p.add_run()
        run.text = plan.overall_caption
        run.font.name = "Arial"
        run.font.size = Pt(13)
        run.font.italic = True
        run.font.color.rgb = RGBColor(60, 60, 60)

        # Speaker notes
        notes = s.notes_slide.notes_text_frame
        ann_listing = "\n\nNumbered annotations:\n" + "\n".join(
            f"{i + 1}. [{a.label}] — {a.explanation}"
            for i, a in enumerate(plan.annotations)
        )
        notes.text = plan.long_explanation + ann_listing

    # Provenance
    try:
        pres.core_properties.comments = (
            "Generated by vaultlab figure-understanding prototype. "
            "Source: car_t_30min_v13.pptx. Annotations are vaultlab's "
            "visual interpretation; full explanation in speaker notes."
        )
    except (AttributeError, ValueError):
        pass

    PPTX_OUT.parent.mkdir(parents=True, exist_ok=True)
    pres.save(PPTX_OUT)
    return PPTX_OUT


